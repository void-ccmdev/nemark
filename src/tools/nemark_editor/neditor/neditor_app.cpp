int Application::run()
{   //--Begin
    NEWindow window;
    NEUI ui;
    NEInput eInput;

    window.create(width, height, title, maximized);
    ui.initialize();
    ui.setTheme(NEUI::EditorThemes::DARK);

    eInput.setShortcuts();

    //--Globals
    globalServer.SetVariable("EDITOR_SHOULD_CLOSE", false);

    //--ANSI
#if(WIN32)
    printWinANSI();
#else
    printLinuxANSI();
#endif

    //--Editor-loop
    while(!window.shouldClose())
    {   
        eInput.processInput(window.getNemarkWindow());

        ui.startUI();
        ui.updateUI();
        window.update();
        ui.endUI();

        bool shouldClose = std::any_cast<bool>(globalServer.GetVariable("EDITOR_SHOULD_CLOSE"));
        if (shouldClose) {
            window.setShouldClose(true);
        }
    }

    //--End

    ui.destroyUI();
    window.close();

    return 0;
}


